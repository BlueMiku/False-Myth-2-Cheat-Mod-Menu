"""Generates tools/fm2mod/equipment_items.inc (+ shop_perks.inc) from the dumped databases.
equipment_items.inc : {id, L"English name"}  for every named entry of UserDB 15 (equipment).  The game's own "get equipment" event 197 takes the id as its 4th argument.
shop_perks.inc      : {id} for every named entry of UserDB 33 (Sebas shop perks) -> runtime table CDB 6 (flag 1 = purchasable)."""
import json, re
D = r"F:\Personal Projjects\FM2\work\wolftl\dump"
OUT = r"F:\Personal Projjects\FM2\tools\fm2mod"
udb = json.load(open(D + r"\db\DataBase.json", encoding="utf-8"))["types"]

def clean(s):
    s = re.sub(r"\\[A-Za-z\-]+\[[^\]]*\]", "", s)      # text control codes like \f[16] \-[02]
    s = s.replace("\\", "").replace('"', "'").strip()
    return s

rows = []
for i, it in enumerate(udb[15]["data"]):
    v = {d["name"]: d["value"] for d in it["data"]}
    nm = clean(v.get("名前", ""))
    if nm: rows.append((i, int(v.get("装備ID種類", 0)), nm))
with open(OUT + r"\equipment_items.inc", "w", encoding="utf-8") as f:
    f.write("// generated by tools/gen_equipment.py: {equipment id, type (UserDB 15 field 2), English name}\n")
    for i, t, nm in rows: f.write('{%d, %d, L"%s"},\n' % (i, t, nm))
print(len(rows), "equipment entries; first:", rows[:3], "last:", rows[-2:])

perks = [i for i, it in enumerate(udb[33]["data"]) if it["name"].strip()]
with open(OUT + r"\shop_perks.inc", "w", encoding="utf-8") as f:
    f.write("// generated by tools/gen_equipment.py: Sebas-shop perk ids (named UserDB 33 entries)\n")
    f.write(",".join(str(i) for i in perks) + ",\n")
print(len(perks), "shop perks")
