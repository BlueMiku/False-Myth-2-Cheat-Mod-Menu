"""Build docs/variables.md from the WolfTL dump (SysDatabase variable-name tables).
ID scheme (confirmed by usage counts in CommonEvent dump): normal var n -> 2000000+n,
spare var k (1-9) item n -> 2000000 + k*100000 + n.
Usage: python -X utf8 build_varmap.py
"""
import json, glob, collections, os
BASE = r"F:\Personal Projjects\FM2"
dump = os.path.join(BASE, "work", "wolftl", "dump")
types = json.load(open(os.path.join(dump, "db", "SysDatabase.json"), encoding="utf-8"))["types"]

# count references per ID in common events
refs = collections.Counter()
for f in glob.glob(os.path.join(dump, "common", "*.json")):
    for c in json.load(open(f, encoding="utf-8"))["commands"]:
        for a in c.get("intArgs", []):
            if 2000000 <= a < 3000000:
                refs[a] += 1

groups = [("通常変数 (normal)", 14, 2000000)] + [(f"予備変数{k} (spare {k})", 14 + k, 2000000 + k * 100000) for k in range(1, 10)]
out = ["# Variable map (SysDatabase names -> Wolf variable IDs)", "",
       "Generated by tools/build_varmap.py. `refs` = how many CommonEvent command args mention the ID.", ""]
for title, ti, base in groups:
    out += [f"## {title} — base {base}", "", "| ID | idx | name | refs |", "|---|---|---|---|"]
    for i, it in enumerate(types[ti]["data"]):
        if it["name"]:
            out.append(f"| {base+i} | {i} | {it['name']} | {refs[base+i]} |")
    out.append("")
open(os.path.join(BASE, "docs", "variables.md"), "w", encoding="utf-8").write("\n".join(out))
print("written", sum(1 for l in out if l.startswith("| 2")), "variables")
